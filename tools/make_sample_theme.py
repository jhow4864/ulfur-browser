#!/usr/bin/env python3
"""Builds sample-themes/Slate.ulfurtheme: a neutral schema 2 pack with generated gradient images (no art, no faces).
Pure stdlib (zlib PNG writer), deterministic output. usage: tools/make_sample_theme.py [out]"""
import json, struct, sys, zlib, zipfile

def png(w, h, f):
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            raw += bytes(f(x / (w - 1), y / (h - 1)))
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))

def lerp(a, b, t): return [round(a[i] + (b[i] - a[i]) * t) for i in range(3)]
TOP, BOTTOM = (0x9C, 0xA3, 0xAF), (0x4B, 0x55, 0x63)  # neutral slate greys

home = png(1080, 2400, lambda x, y: lerp(TOP, BOTTOM, min(1, 0.8 * y + 0.2 * x)))
toolbar = png(1440, 256, lambda x, y: lerp(TOP, BOTTOM, 0.3 + 0.4 * x))
header = png(1440, 480, lambda x, y: lerp(TOP, BOTTOM, 0.5 * x + 0.5 * y))

theme = {
    "format": "ulfurtheme", "schema": 2, "name": "Slate (sample)", "author": "Ulfur", "version": "1.0", "base": "ash",
    "colors": {
        "dark": {"accent": "#8FA3BF", "accentStart": "#A9B8CC", "accentEnd": "#7A8FAD", "onAccent": "#0E0E12",
                 "accentText": "#A9B8CC", "surfaceTint": "#262A33", "eye": "#C9D3E0",
                 "background": "#15171C", "surface": "#1D2027", "surfaceVariant": "#262A33", "text": "#EDEFF3",
                 "textSecondary": "#A7ADBA", "toolbar": "#1A1D23", "onToolbar": "#EDEFF3", "divider": "#2E323C"},
        "light": {"accentText": "#3D5272", "surfaceTint": "#E3E7EE",
                  "background": "#F3F4F6", "surface": "#FFFFFF", "surfaceVariant": "#E8EAEE", "text": "#16181D",
                  "textSecondary": "#545A66", "toolbar": "#E9EBEF", "onToolbar": "#16181D", "divider": "#D5D8DE"},
    },
    "images": {
        "home": {"file": "images/home.png", "fit": "cover", "focus": {"x": 0.5, "y": 0.35}, "scrim": 0.3, "scrimAuto": True, "scrimMax": 0.85},
        "toolbar": {"file": "images/toolbar.png", "fit": "cover", "scrim": 0.4, "scrimAuto": True, "scrimMax": 0.85},
        "header": {"file": "images/header.png", "fit": "cover", "focus": {"x": 0.3, "y": 0.6}, "scrim": 0.3, "scrimAuto": True, "scrimMax": 0.85},
    },
}
out = sys.argv[1] if len(sys.argv) > 1 else "sample-themes/Slate.ulfurtheme"
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    def add(name, data):
        zi = zipfile.ZipInfo(name, (2026, 10, 12, 0, 0, 0)); zi.compress_type = zipfile.ZIP_DEFLATED
        z.writestr(zi, data)
    add("theme.json", json.dumps(theme, indent=2))
    add("README.txt", "Neutral sample pack for testing theme packs v2 (generated by tools/make_sample_theme.py).\n")
    add("images/home.png", home); add("images/toolbar.png", toolbar); add("images/header.png", header)
print(out)
